#!/usr/bin/env python3
"""TAESC command-line driver facade.

For now this script dispatches TAESC driver tasks to the bundled LibRPA driver.
It reads a LibRPA-like ``taesc.in`` file from the current working directory,
validates the requested task, writes a generated ``librpa.in`` file, and
launches ``chi0_main.exe`` from a TAESC build directory.
"""

from __future__ import annotations

import argparse
from collections import OrderedDict
from dataclasses import dataclass
import os
from pathlib import Path
import shlex
import subprocess
import sys
from typing import Iterable


LIBRPA_DRIVER_NAME = "chi0_main.exe"

IMPOSED_LIBRPA_PARAMS = OrderedDict(
    [
        ("output_dir", "taesc.d"),
        ("parallel_routing", "libri"),
    ]
)

SUPPORTED_LIBRPA_TASKS = {
    "rpa": "RPA correlation energy",
    "g0w0": "One-shot G0W0 quasi-particle energies on the k-grid",
    "g0w0_band": "One-shot G0W0 quasi-particle band structure",
    "exx": "Exact exchange on the k-grid",
    "exx_band": "Exact exchange on band k-points",
    "print_minimax": "Print minimax time-frequency grids",
}


class DriverError(RuntimeError):
    """User-facing driver error."""


@dataclass(frozen=True)
class ParsedInput:
    path: Path
    params: "OrderedDict[str, tuple[str, str]]"

    def get(self, key: str) -> str | None:
        item = self.params.get(normalize_key(key))
        if item is None:
            return None
        return item[1]


def normalize_key(key: str) -> str:
    return key.strip().lower()


def normalize_task(task: str) -> str:
    return strip_optional_quotes(task).strip().lower()


def strip_optional_quotes(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
        return value[1:-1]
    return value


def strip_comment(line: str) -> str:
    for index, char in enumerate(line):
        if char in "#!":
            return line[:index]
    return line


def parse_taesc_input(path: Path) -> ParsedInput:
    if not path.is_file():
        raise DriverError(f"input file does not exist: {path}")

    params: "OrderedDict[str, tuple[str, str]]" = OrderedDict()
    for lineno, raw_line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = strip_comment(raw_line).strip()
        if not line:
            continue
        if "=" not in line:
            raise DriverError(f"{path}:{lineno}: expected a 'key = value' assignment")

        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        key_norm = normalize_key(key)
        if not key_norm:
            raise DriverError(f"{path}:{lineno}: empty parameter name")
        if not value:
            raise DriverError(f"{path}:{lineno}: empty value for parameter '{key}'")

        if key_norm in params:
            del params[key_norm]
        params[key_norm] = (key, value)

    return ParsedInput(path=path, params=params)


def validate_task(parsed: ParsedInput) -> str:
    task_raw = parsed.get("task")
    if task_raw is None:
        raise DriverError("taesc.in must define a 'task' parameter")

    task = normalize_task(task_raw)
    if task in SUPPORTED_LIBRPA_TASKS:
        return task

    supported = ", ".join(sorted(SUPPORTED_LIBRPA_TASKS))
    raise DriverError(f"unknown task '{task_raw}'. Supported tasks: {supported}")


def resolve_input_dir(parsed: ParsedInput, work_dir: Path) -> str:
    input_dir = parsed.get("input_dir")
    base_dir = parsed.path.parent.resolve()
    if input_dir is None:
        return os.path.relpath(base_dir, start=work_dir.resolve())

    input_dir_path = Path(strip_optional_quotes(input_dir)).expanduser()
    if input_dir_path.is_absolute():
        return str(input_dir_path.resolve())

    input_dir_path = base_dir / input_dir_path
    return os.path.relpath(input_dir_path.resolve(), start=work_dir.resolve())


def write_librpa_input(parsed: ParsedInput, task: str, work_dir: Path) -> Path:
    params: "OrderedDict[str, tuple[str, str]]" = OrderedDict(parsed.params)
    params.pop("task", None)
    params.pop("input_dir", None)
    for key in IMPOSED_LIBRPA_PARAMS:
        params.pop(key, None)

    librpa_input = work_dir / "librpa.in"
    work_dir.mkdir(parents=True, exist_ok=True)

    lines = [
        "# Generated by TAESC driver from " + str(parsed.path.resolve()),
        "# Edit taesc.in instead of this file when running through TAESC.",
        f"task = {task}",
        f"input_dir = {resolve_input_dir(parsed, work_dir)}",
    ]
    lines.extend(f"{key} = {value}" for key, value in IMPOSED_LIBRPA_PARAMS.items())
    lines.extend(f"{key} = {value}" for key, value in params.values())
    librpa_input.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return librpa_input


def find_librpa_driver(build_dir: Path) -> Path:
    build_dir = build_dir.expanduser().resolve()
    if not build_dir.is_dir():
        raise DriverError(f"build directory does not exist: {build_dir}")

    candidates = [
        build_dir / LIBRPA_DRIVER_NAME,
        build_dir / "bin" / LIBRPA_DRIVER_NAME,
        build_dir / "src" / "LibRPA" / LIBRPA_DRIVER_NAME,
        build_dir / "src" / "LibRPA" / "driver" / LIBRPA_DRIVER_NAME,
    ]
    for candidate in candidates:
        if candidate.is_file():
            return candidate

    matches = sorted(
        (path for path in build_dir.rglob(LIBRPA_DRIVER_NAME) if path.is_file()),
        key=lambda path: (len(path.parts), str(path)),
    )
    if matches:
        return matches[0]

    raise DriverError(
        f"could not find {LIBRPA_DRIVER_NAME} under build directory {build_dir}"
    )


def launcher_np_args(launcher: Iterable[str], np: int | None) -> list[str]:
    if np is None:
        return []
    if np < 1:
        raise DriverError("--np must be a positive integer")

    launcher_list = list(launcher)
    launcher_name = Path(launcher_list[0]).name if launcher_list else "mpirun"
    # slurm
    if launcher_name in ["srun", ]:
        return []
    if launcher_name in ["jsrun", ]:
        return ["-n", str(np)]
    return ["-np", str(np)]


def build_command(driver_exe: Path, launcher: str | None, np: int | None) -> list[str]:
    if launcher is None and np is None:
        return [str(driver_exe)]

    if launcher is None:
        launcher_parts = ["mpirun"]
    else:
        launcher_parts = shlex.split(launcher)
        if not launcher_parts:
            raise DriverError("--launcher was provided but did not contain a command")

    return launcher_parts + launcher_np_args(launcher_parts, np) + [str(driver_exe)]


def format_command(command: Iterable[str]) -> str:
    return " ".join(shlex.quote(part) for part in command)


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="TAESC driver facade. Reads ./taesc.in and dispatches to LibRPA.",
    )
    parser.add_argument(
        "-B",
        "--build-dir",
        required=True,
        help="TAESC build directory containing the LibRPA driver chi0_main.exe",
    )
    parser.add_argument(
        "-n",
        "--np",
        type=int,
        help="number of MPI ranks; with no --launcher, uses mpirun -np NP",
    )
    parser.add_argument(
        "--launcher",
        help="MPI launcher command, for example 'mpirun' or 'srun'",
        default="mpirun",
    )
    parser.add_argument(
        "-W",
        "--work-dir",
        help="directory where generated librpa.in is written and LibRPA runs; "
        "default is the directory containing the TAESC input file",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="write librpa.in and print the command without launching LibRPA",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)

    try:
        input_path = (Path.cwd() / "taesc.in").resolve()
        parsed = parse_taesc_input(input_path)
        task = validate_task(parsed)
        build_dir = Path(args.build_dir)
        driver_exe = find_librpa_driver(build_dir)
        work_dir = (
            Path(args.work_dir).expanduser().resolve()
            if args.work_dir is not None
            else input_path.parent
        )
        generated_input = write_librpa_input(parsed, task, work_dir)
        command = build_command(driver_exe, args.launcher, args.np)

        print(f"TAESC task       : {task} ({SUPPORTED_LIBRPA_TASKS[task]})")
        print(f"LibRPA driver    : {driver_exe}")
        print(f"Work directory   : {work_dir}")
        print(f"Generated input  : {generated_input}")
        print(f"Command          : {format_command(command)}", flush=True)

        returncode = (
            0
            if args.dry_run
            else subprocess.run(command, cwd=work_dir, check=False).returncode
        )
    except (DriverError, OSError) as exc:
        print(f"taesc-driver: error: {exc}", file=sys.stderr)
        returncode = 2

    print("TAESC finished successfully" if returncode == 0 else "Error: TAESC failed")
    return returncode


if __name__ == "__main__":
    raise SystemExit(main())
